export function CategoryIcon({ category, size }: { category: Category | null; size?: number }) {
  switch (category) {
    case "image":
      return <ImageIcon size={size} />;
    case "audio":
      return <AudioIcon size={size} />;
    case "video":
      return <VideoIcon size={size} />;
    case "subtitle":
      return <SubtitleIcon size={size} />;
    case "archive":
      return <ArchiveIcon size={size} />;
    default:
      return <DocIcon size={size} />;
  }
}
